<p>The Young Innovator and Entrepreneur Award in One Health recognize and honour an emerging innovator/entrepreneur/start-up founder/young professional actively engaged in One Health-related fields.</p>

<h3 style="text-decoration: underline;">PROFORMA</h3>

<p class="section-title">1. ELIGIBILITY CRITERIA</p>
<p>The nominee should:</p>
<ol>
    <li>Be an emerging innovator, entrepreneur, start-up founder, or young professional working in a One Health-related area.</li>
    <li>Demonstrate significant contribution to the integration of human health, animal health and environmental/ecosystem health.</li>
    <li>Have developed any of the innovations including technology, product, service, process, platform, enterprise, or social innovation addressing a One Health challenge.</li>
    <li>Demonstrate potential for translation, scalability, societal impact, or commercialization.</li>
    <li>Be 40 years of age or below as on the last date of submission.</li>
    <li>The innovation/enterprise should preferably demonstrate evidence of implementation, validation, adoption, intellectual property, commercialization, or measurable community impact.</li>
</ol>

